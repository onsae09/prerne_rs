% ============================================================
% Initial conditions
% ============================================================

dx = 0.1;
dy = 0.1;
dz = 0.1;
dt = 0.01;

Nx = 20;
Ny = 20;
Nz = 20;
Nt = 100;

T_initial = 303.0;      % K
p_initial = 101325.0;   % Pa

T = ones(Nx, Ny, Nz) * T_initial;
p = ones(Nx, Ny, Nz) * p_initial;


% ============================================================
% Air properties
% ============================================================

properties = air_properties_fast(T, p);

rho = properties.rho;   % kg/m^3
C_p = properties.Cp;    % J/(kg*K)
mu  = properties.mu;    % Pa*s
k   = properties.k;     % W/(m*K)
Pr  = properties.Pr;    % dimensionless


% ============================================================
% Fast air property calculation
% ============================================================

function properties = air_properties_fast(T, P)

    % --------------------------------------------------------
    % Input checks
    % --------------------------------------------------------

    if ~isequal(size(T), size(P))
        error('T and P must have the same size.');
    end

    if any(T(:) < 200.0) || any(T(:) > 400.0)
        error('Temperature must be between 200 K and 400 K.');
    end

    if any(P(:) <= 0)
        error('Pressure must be positive.');
    end


    % --------------------------------------------------------
    % Constants
    % --------------------------------------------------------

    R_u = 8.31446261815324;   % J/(mol*K)

    % Molar masses [kg/mol]
    M_N2 = 28.0134e-3;
    M_O2 = 31.9988e-3;
    M_Ar = 39.948e-3;


    % --------------------------------------------------------
    % Dry-air composition
    %
    % Mole fractions
    % --------------------------------------------------------

    x_N2 = 0.78084;
    x_O2 = 0.20946;
    x_Ar = 0.00934;

    % Normalize because trace gases such as CO2 are omitted
    x_sum = x_N2 + x_O2 + x_Ar;

    x_N2 = x_N2 / x_sum;
    x_O2 = x_O2 / x_sum;
    x_Ar = x_Ar / x_sum;


    % --------------------------------------------------------
    % Mixture molar mass
    % --------------------------------------------------------

    M_air = ...
          x_N2 * M_N2 ...
        + x_O2 * M_O2 ...
        + x_Ar * M_Ar;

    R_air = R_u / M_air;


    % --------------------------------------------------------
    % Density
    %
    % Ideal gas equation
    %
    % rho = P / (R_air * T)
    % --------------------------------------------------------

    rho = P ./ (R_air .* T);


    % --------------------------------------------------------
    % Cp using NASA9 polynomial
    %
    % Cp/R =
    % a1/T^2 + a2/T + a3
    % + a4*T + a5*T^2 + a6*T^3 + a7*T^4
    %
    % Valid here for 200 K <= T <= 1000 K
    % --------------------------------------------------------


    % N2, NASA9, 200-1000 K
    N2 = [ ...
         2.210371497e4, ...
        -3.818461820e2, ...
         6.082738360, ...
        -8.530914410e-3, ...
         1.384646189e-5, ...
        -9.625793620e-9, ...
         2.519705809e-12];


    % O2, NASA9, 200-1000 K
    O2 = [ ...
        -3.425563420e4, ...
         4.847000970e2, ...
         1.119010961, ...
         4.293889240e-3, ...
        -6.836300520e-7, ...
        -2.023372700e-9, ...
         1.039040018e-12];


    % --------------------------------------------------------
    % Precompute temperature terms
    % --------------------------------------------------------

    invT  = 1.0 ./ T;
    invT2 = invT .* invT;

    T2 = T .* T;
    T3 = T2 .* T;
    T4 = T2 .* T2;


    % --------------------------------------------------------
    % Dimensionless Cp/R
    % --------------------------------------------------------

    CpR_N2 = ...
          N2(1) .* invT2 ...
        + N2(2) .* invT ...
        + N2(3) ...
        + N2(4) .* T ...
        + N2(5) .* T2 ...
        + N2(6) .* T3 ...
        + N2(7) .* T4;


    CpR_O2 = ...
          O2(1) .* invT2 ...
        + O2(2) .* invT ...
        + O2(3) ...
        + O2(4) .* T ...
        + O2(5) .* T2 ...
        + O2(6) .* T3 ...
        + O2(7) .* T4;


    % Argon: monatomic ideal gas
    CpR_Ar = 2.5;


    % --------------------------------------------------------
    % Mixture molar Cp
    % --------------------------------------------------------

    Cp_molar = R_u .* ( ...
          x_N2 .* CpR_N2 ...
        + x_O2 .* CpR_O2 ...
        + x_Ar .* CpR_Ar);


    % --------------------------------------------------------
    % Mass-specific Cp
    % --------------------------------------------------------

    Cp = Cp_molar ./ M_air;


    % --------------------------------------------------------
    % Dynamic viscosity
    %
    % Sutherland equation
    % --------------------------------------------------------

    T_ref  = 273.15;
    mu_ref = 1.716e-5;
    S      = 111.0;

    mu = mu_ref .* ...
        (T ./ T_ref).^1.5 .* ...
        ((T_ref + S) ./ (T + S));


    % --------------------------------------------------------
    % Prandtl number approximation
    %
    % Good approximation around this temperature range
    % --------------------------------------------------------

    Pr = 0.71;


    % --------------------------------------------------------
    % Thermal conductivity
    %
    % k = Cp * mu / Pr
    % --------------------------------------------------------

    k = Cp .* mu ./ Pr;


    % --------------------------------------------------------
    % Output
    % --------------------------------------------------------

    properties.rho = rho;
    properties.Cp  = Cp;
    properties.mu  = mu;
    properties.k   = k;
    properties.Pr  = Pr;

end